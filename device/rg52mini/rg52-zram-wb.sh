#!/system/bin/sh
# Вытеснение содержимого zram на подложку по давлению памяти.
#
# Штатная служба ZramWriteback в каркасе для этого не годится: она помечает
# страницы неиспользуемыми раз в несколько минут и вытесняет их заданиями
# планировщика раз в часы (ro.zram.mark_idle_delay_mins, first_wb_delay_mins,
# periodic_wb_delay_hours). Игра, которая забирает 1,8 ГБ за минуту, умирает
# задолго до первого срабатывания.
#
# Здесь то же самое, но по факту нехватки: как только доступной памяти меньше
# порога, все страницы zram помечаются неиспользуемыми и уходят на подложку.
# Замерено на устройстве: за две минуты игры через подложку прошло 700 МБ,
# которые иначе занимали бы память в сжатом виде, и игра осталась жива.
#
# Свойства:
#   persist.rg52.zram.wb_threshold_mb   порог в МБ, 0 — не вытеснять
#
# Служба работает только при включённом экране (запускается и останавливается по
# sys.screen.state). Опрос раз в две секунды при погашенном экране мешал бы
# устройству засыпать, а смысла в нём там нет: тяжёлых приложений на переднем
# плане нет по определению.

set -u

TAG=rg52-zram-wb
SYS=/sys/block/zram0

THRESH=$(getprop persist.rg52.zram.wb_threshold_mb)
case "$THRESH" in
    ''|*[!0-9]*) THRESH=0 ;;
esac
CARD=$(getprop persist.gammaos.swap.size_mb)
case "$CARD" in
    ''|*[!0-9]*) CARD=0 ;;
esac

# Ноль в любом из двух полей означает одно и то же: вытеснения нет. Выходим, а
# не ждём подложку, которой не будет.
[ "$THRESH" = 0 ] && exit 0
[ "$CARD" = 0 ] && exit 0
[ -e "$SYS/writeback" ] || exit 0

log -p i -t "$TAG" "сторож вытеснения запущен, порог ${THRESH} МБ"

while :; do
    # Подложку настраивает rg52-zram.sh, и он может ещё не отработать: обе
    # службы поднимаются по одному и тому же изменению свойства. Ждём её.
    if [ "$(cat "$SYS/backing_dev" 2>/dev/null)" = "none" ]; then
        sleep 5
        continue
    fi
    AVAIL=$(( $(awk '/MemAvailable/{print $2}' /proc/meminfo) / 1024 ))
    if [ "$AVAIL" -lt "$THRESH" ]; then
        echo all > "$SYS/idle" 2>/dev/null
        echo idle > "$SYS/writeback" 2>/dev/null
    fi
    sleep 2
done
