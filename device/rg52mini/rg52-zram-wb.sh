#!/system/bin/sh
# Вытеснение содержимого zram на подложку по давлению памяти.
#
# Штатная служба ZramWriteback в каркасе для этого не годится: она помечает
# страницы неиспользуемыми раз в несколько минут и вытесняет их заданиями
# планировщика раз в часы (ro.zram.mark_idle_delay_mins, first_wb_delay_mins,
# periodic_wb_delay_hours). Игра, которая забирает 1,8 ГБ за минуту, умирает
# задолго до первого срабатывания.
#
# Здесь то же самое, но по факту нехватки: как только доступной памяти меньше
# порога, все страницы zram помечаются неиспользуемыми и уходят на подложку.
# Замерено на устройстве: за две минуты игры через подложку прошло 700 МБ,
# которые иначе занимали бы память в сжатом виде, и игра осталась жива.
#
# Свойства:
#   persist.rg52.zram.wb_threshold_mb   порог в МБ, 0 — не вытеснять
#
# Служба работает только при включённом экране (запускается и останавливается по
# sys.screen.state). Опрос раз в две секунды при погашенном экране мешал бы
# устройству засыпать, а смысла в нём там нет: тяжёлых приложений на переднем
# плане нет по определению.

set -u

TAG=rg52-zram-wb
SYS=/sys/block/zram0

num() {   # $1 значение, $2 запасное
    case "$1" in
        ''|*[!0-9]*) echo "$2" ;;
        *) echo "$1" ;;
    esac
}

[ -e "$SYS/writeback" ] || { log -p i -t "$TAG" "вытеснение этим ядром не поддерживается"; sleep infinity; }

# Пока вытеснять некуда — ждём, а не выходим.
#
# Выход здесь выглядел естественно: ноль в размере подложки или в пороге
# означает, что делать нечего. Но служба не oneshot, и init поднимает её снова
# через пять секунд, снова, снова - на свежем образе с заводскими настройками
# (подложки нет) это бесконечный запуск процесса каждые пять секунд. Заметно в
# getprop: init.svc.rg52_zram_wb навсегда остаётся в состоянии restarting.
#
# Поэтому просто спим и перечитываем настройки: подложку могут включить на
# ходу, и тогда сторож начнёт работать сам, без перезапуска службы.
while :; do
    THRESH=$(num "$(getprop persist.rg52.zram.wb_threshold_mb)" 0)
    CARD=$(num "$(getprop persist.rg52.zram.backing_mb)" 0)
    if [ "$THRESH" != 0 ] && [ "$CARD" != 0 ]; then
        break
    fi
    sleep 30
done

log -p i -t "$TAG" "сторож вытеснения запущен, порог ${THRESH} МБ"

# Цикл - на встроенных командах оболочки. Каждый внешний процесс (cat, awk) на
# этом устройстве стоит 15-18 мс процессора, и прежний опрос - cat, awk и sleep
# раз в две секунды - съедал около 2,7 % ядра на одни только запуски. read
# читает файлы без fork, внешним остаётся только sleep.
read_avail() {   # AVAIL - MemAvailable в МБ
    AVAIL=0
    while read -r k v rest; do
        case $k in MemAvailable:) AVAIL=$(( v / 1024 )); return ;; esac
    done < /proc/meminfo
}

while :; do
    # Подложку настраивает rg52-zram.sh, и он может ещё не отработать: обе
    # службы поднимаются по одному и тому же изменению свойства. Ждём её.
    read -r BD 2>/dev/null < "$SYS/backing_dev" || BD=none
    if [ "$BD" = none ]; then
        sleep 5
        continue
    fi
    read_avail
    if [ "$AVAIL" -lt "$THRESH" ]; then
        echo all > "$SYS/idle" 2>/dev/null
        echo idle > "$SYS/writeback" 2>/dev/null
    fi
    # Пока до порога больше его самого, смотрим реже: даже самая жадная игра
    # из замеров (1,8 ГБ за минуту) не съест такой запас за шесть секунд.
    if [ "$AVAIL" -gt $(( THRESH * 2 )) ]; then
        sleep 6
    else
        sleep 2
    fi
done
