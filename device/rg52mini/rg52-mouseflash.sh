#!/system/bin/sh
# Короткое моргание экраном при переключении режима эмуляции мыши.
#
# Всплывающей надписи gammapad мало: в полноэкранной игре или в эмуляторе её
# может быть не видно, а переключение режима нужно подтверждать однозначно.
# Инверсия цветов заметна при любом содержимом экрана. Так же было сделано в
# rgp2pad, откуда пользователи сюда и переходят.
#
# Почему отдельной службой, а не прямо в gammapad: вызов system() с командой
# settings оттуда не работает. Оболочка и cmd запускаются (видно по audit в
# логе), но значение настройки не меняется, а разобрать причину нечем -
# вывод службы init уходит в /dev/null, а команда ещё и уводится в фон, так
# что её код возврата до демона не доходит. Здесь же всё видно в логе.
#
# Запускается по изменению sys.gammaos.gamepad.mouse_active, см.
# rg52-mouseflash.rc. Служба работает от пользователя shell в домене
# u:r:shell:s0 - ровно то окружение, в котором эта команда заведомо работает
# (проверено через adb shell).
#
# Выключается: setprop persist.rg52.mouse_flash 0

TAG=rg52-mouseflash
KEY=accessibility_display_inversion_enabled

if [ "$(getprop persist.rg52.mouse_flash 1)" = "0" ]; then
    exit 0
fi

# Длительность инверсии в секундах. 0,1 с - это около шести кадров при 60 Гц:
# видно отчётливо, но уже не тормозит. Значение снаружи, потому что подобрать
# его на глаз проще без пересборки: setprop persist.rg52.mouse_flash_sec 0.25
#
# К этому времени добавляется около 160 мс накладных расходов: каждая команда
# settings поднимает cmd и идёт через binder, это примерно 80 мс на вызов
# (замерено на устройстве). Плюс сам sleep на этом ядре просыпается с запасом:
# sleep 0.4 занимает 487 мс, то есть заказанное время выходит примерно на
# четверть длиннее. С 0,1 с видимая инверсия получается около 200 мс. Первая
# версия с паузой 0,4 с тянулась на глаз больше секунды.
DUR=$(getprop persist.rg52.mouse_flash_sec 0.1)
case "$DUR" in
    ''|*[!0-9.]*) DUR=0.1 ;;
esac

# Текущее значение запоминаем и возвращаем: инверсия - обычная настройка
# специальных возможностей, и если пользователь включил её намеренно, мы не
# должны её сбрасывать. Заодно моргание работает в обе стороны.
cur=$(settings get secure $KEY)
case "$cur" in
    1) cur=1; other=0 ;;
    *) cur=0; other=1 ;;
esac

if ! settings put secure $KEY $other; then
    log -p w -t $TAG "не удалось включить инверсию"
    exit 1
fi

sleep "$DUR"

if ! settings put secure $KEY $cur; then
    log -p w -t $TAG "не удалось вернуть инверсию в $cur"
    exit 1
fi

log -t $TAG "моргнули (mouse_active=$(getprop sys.gammaos.gamepad.mouse_active))"
