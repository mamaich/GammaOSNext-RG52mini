#!/vendor/bin/sh
# Плата ревизии A несёт RK915, ревизии B — AIC8800D80. Чипы сидят на одном
# слоте SDIO и делят вывод питания, поэтому загружать оба драйвера подряд
# нельзя: тот, что грузится вторым, снимает питание и выбивает первый.
#
# rk915 грузится раньше, из init.insmod.cfg. Если он нашёл свой чип, интерфейс
# уже есть — AIC8800 не трогаем. Если нет, догружаем AIC8800.
#
# Почему не просто ждём интерфейс. Ожидание вслепую стоит четырёх секунд на
# ревизии B, то есть у большинства, и эти секунды не бесплатны: прошивка
# AIC8800 поднимается ещё около девяти секунд после insmod, а Android начинает
# подключаться, как только видит wlan0. Задержка сдвигала готовность прошивки
# ровно в тот момент, когда каркас уже пробует связаться с точкой доступа, и
# попытка отбивалась изнутри драйвера:
#
#     CTRL-EVENT-ASSOC-REJECT bssid=00:00:00:00:00:00 status_code=30
#
# Нулевой BSSID здесь и означает, что отказ не от точки доступа. После кода 30
# Android ждёт до следующей попытки пять минут — столько устройство и оставалось
# без сети после каждой загрузки.
#
# Поэтому ждём только тогда, когда есть чего ждать. Если rk915 не значится в
# /proc/modules, значит его инициализация провалилась (на ревизии B так и
# происходит: rk915_init: platform_bus_init failed), интерфейса от него не будет
# никогда, и ждать нечего — грузим AIC8800 сразу.

have_wlan() {
    for n in /sys/class/net/wlan*; do
        [ -e "$n" ] && return 0
    done
    return 1
}

rk915_loaded() {
    grep -q '^rk915 ' /proc/modules 2>/dev/null
}

if have_wlan; then
    log -t wifi_pick "интерфейс уже есть, AIC8800 не нужен"
    exit 0
fi

if rk915_loaded; then
    # Модуль в памяти — значит он либо нашёл чип, либо ещё разбирается.
    # Даём ему время поднять интерфейс.
    i=0
    while [ $i -lt 20 ]; do
        if have_wlan; then
            log -t wifi_pick "RK915 поднял интерфейс, AIC8800 не нужен"
            exit 0
        fi
        i=$((i + 1))
        sleep 0.2
    done
    log -t wifi_pick "RK915 в памяти, но интерфейса нет, гружу AIC8800"
else
    log -t wifi_pick "RK915 не загрузился, ждать нечего, гружу AIC8800 сразу"
fi

insmod /vendor/lib/modules/aic8800_bsp.ko
insmod /vendor/lib/modules/aic8800_fdrv.ko
