#!/system/bin/sh
# Сторож пустого экрана в режиме nano.
#
# Зачем. Оболочка nano запускает приложение на весь экран и прячется сама. Если
# приложение ломается, остаётся чёрный экран и вернуться некуда: приложение
# живо, фокус у него, меню спрятано. Штатный выход есть - долгое нажатие
# выключателя поднимает меню, - но о нём надо знать. Сторож делает то же самое
# сам.
#
# Почему именно по картинке. Дешёвые признаки не работают, проверено на живом
# случае с RetroArch:
#
#   нагрузка       приложение крутило около 30% процессора;
#   счётчик кадров SurfaceFlinger исправно рос (frame=22519 -> 22522);
#   /dev/graphics/fb0 не отражает собранный кадр - там мусор, одинаковый и на
#                  чёрном экране, и на меню.
#
# То есть приложение рисовало - просто рисовало чёрное. Отличить это можно
# только по самому кадру. Признак берём косвенный и дешёвый в разборе: PNG
# полностью чёрного экрана сжимается в 5 КБ, а любой картинки - в 80 КБ.
#
# Чего это стоит. Снимок экрана - около 440 мс, и это сам захват, а не сжатие
# (проверено: сырой снимок стоит столько же). Поэтому опрос редкий, раз в 30
# секунд, и нужно два подряд чёрных снимка - то есть срабатывание примерно
# через минуту. Во время игры это один снимок в полминуты; если мешает,
# выключается одним свойством.
#
# Настройки (читаются каждый круг, перезапуск не нужен):
#     persist.rg52.nanowatch         1 - включён, 0 - выключен
#     persist.rg52.nanowatch_poll    период опроса, секунд (30)
#     persist.rg52.nanowatch_hits    сколько чёрных снимков подряд ждать (2)
#     persist.rg52.nanowatch_bytes   порог "пустого" снимка в байтах (12000)

TAG=rg52-nanowatch
BL=/sys/class/backlight/backlight/bl_power

hits=0
fired=0

num() {   # $1 - значение, $2 - запасное
    case "$1" in
        ''|*[!0-9]*) echo "$2" ;;
        *) echo "$1" ;;
    esac
}

log -t $TAG "сторож запущен"

while true; do
    poll=$(num "$(getprop persist.rg52.nanowatch_poll 30)" 30)
    sleep "$poll"

    # Выключен, вышли из nano, приложения нет, меню уже на экране или экран
    # погашен - сбрасываем счёт и ждём дальше. Всё это дешёвые проверки, снимок
    # экрана до них не доходит.
    if [ "$(getprop persist.rg52.nanowatch 1)" = "0" ] ||
       [ "$(getprop sys.gammaos.minimal_boot)" != "1" ] ||
       [ "$(getprop sys.gammaos.nano.app_launched)" != "1" ] ||
       [ "$(getprop sys.gammaos.nano.show_overlay)" != "0" ] ||
       [ "$(cat $BL 2>/dev/null)" != "0" ]; then
        hits=0
        fired=0
        continue
    fi

    size=$(screencap -p 2>/dev/null | wc -c)
    limit=$(num "$(getprop persist.rg52.nanowatch_bytes 12000)" 12000)

    # Пустой снимок бывает и при ошибке захвата - тогда он нулевой, и это не
    # повод поднимать меню.
    if [ -z "$size" ] || [ "$size" -lt 1000 ]; then
        continue
    fi

    if [ "$size" -ge "$limit" ]; then
        hits=0
        fired=0
        continue
    fi

    hits=$((hits + 1))
    need=$(num "$(getprop persist.rg52.nanowatch_hits 2)" 2)

    if [ "$hits" -ge "$need" ] && [ "$fired" = "0" ]; then
        pkg=$(getprop sys.gammaos.nano.launch_app)
        log -p w -t $TAG "экран пуст ($size байт) $hits раза подряд, приложение $pkg - поднимаю меню"
        setprop sys.gammaos.nano.show_overlay 1
        fired=1
    fi
done
