#!/system/bin/sh
# Защита от перезапуска консоли на почти пустой батарее.
#
# Что происходит. Ниже примерно 3,7 В покоя (по таблице OCV из дерева это около
# 35 % настоящего заряда; граница зависит от температуры) батарея не держит пиков
# тока: VSYS проседает ниже порога VB_UV, который ставит u-boot (2,9 В, рег. 0xF1),
# и RK817 перезапускает консоль через RESETB - source: on=0x10, off=0x08, журнал в
# pstore обрывается без паники. Главный потребитель - внешний усилитель динамика на
# большой громкости; процессор только добавляет. Проверено 18.10.2026 на ревизии B
# (журнал опытов - doc/rg52mini/02-план.md), при 3,64-3,66 В покоя:
#
#   PSP-демо на полной громкости, любые частоты (2016, 1416, powersave)  перезапуск
#   то же, громкость на 10 дБ ниже                                      перезапуск
#   то же, громкость на 13,5 дБ ниже                                    нет
#   та же игра без звука; 4 ядра на 2016 МГц без звука                  нет
#   4 ядра на 2016 или 1800 МГц + включение динамика с тоном           перезапуск
#   то же на 1608 и 1416 МГц                                            нет
#
# На том же железе dArkOS сбоит так же, если поднять ЦАП к 0 дБ; по умолчанию у
# неё ЦАП на -20 дБ, поэтому там этого не видно. Жалоба с ревизии A (перезагрузка
# при отключении USB на 20-25 %) - частный случай: при смене питания Android разом
# грузит процессор и открывает поток на динамик под звук зарядки.
#
# Что здесь делается.
#
# 1. Звук зарядки выключается один раз (persist.rg52.chgsound_off). На чистой
#    установке он и так выключен по умолчанию (оверлей SettingsProvider,
#    def_charging_sounds_enabled), здесь - для обновления по воздуху. Включивший его
#    обратно в настройках получит своё: отметка не даёт выключать повторно.
#
# 2. Раз в 20 с оценивается напряжение батареи без нагрузки: voltage_now плюс ток
#    разряда или минус ток заряда, умноженный на сопротивление цепи. Зарядку при этом
#    не учитываем (решение владельца): от порта ПК (450 мА) пики всё равно идут из
#    батареи, а при отключении кабеля защита должна уже стоять. Ниже порога ставится
#    sys.rg52.lowbat=1, обратно - выше порога + 50 мВ два замера подряд. Тогда:
#    - AudioService не пускает громкость динамика выше persist.rg52.lowbat.vol_max
#      (12 из 25, 15,8 дБ ниже максимума), а громкость выше опускает; выключатель -
#      persist.rg52.lowbat.vol_limit в GammaOS Toolbox. Наушники и HDMI не трогаются.
#      О смене состояния AudioService узнаёт по рассылке LOWBAT_CHANGED (и сам
#      перечитывает свойства по ACTION_BATTERY_CHANGED);
#    - rg52-perf.sh может ограничить процессор частотой persist.rg52.lowbat.cpu_khz
#      в любом режиме. По умолчанию не ограничивает (решение владельца: только
#      громкость; без звука ядра на 2016 МГц перезапуска не давали).
#    Таймер sleep консоль из сна не будит: в сне цикл стоит.
#
# Настройки (действуют без перезапуска, со следующего замера):
#
#     persist.rg52.lowbat.mv        порог OCV, мВ (по умолчанию 3750); 0 - выключить всё
#     persist.rg52.lowbat.vol_limit 1 - ограничивать громкость динамика, 0 - нет
#     persist.rg52.lowbat.vol_max   потолок громкости динамика, из 25 (12)
#     persist.rg52.lowbat.cpu_khz   потолок процессора, кГц (0 - не ограничивать)
#     persist.rg52.lowbat.res_mohm  сопротивление батареи и цепи, мОм (150)

set -u

B=/sys/class/power_supply/battery

num() { case "$1" in ''|*[!0-9]*) echo "$2" ;; *) echo "$1" ;; esac; }

if [ "$(getprop persist.rg52.chgsound_off)" != 1 ]; then
    if settings put secure charging_sounds_enabled 0; then
        setprop persist.rg52.chgsound_off 1
        log -t rg52-lowbat "charging sounds disabled"
    fi
fi

state=$(getprop sys.rg52.lowbat)
[ "$state" = 1 ] || state=0
high=0
while :; do
    mv=$(num "$(getprop persist.rg52.lowbat.mv)" 3750)
    res=$(num "$(getprop persist.rg52.lowbat.res_mohm)" 150)
    want=$state
    ocv=-
    if [ "$mv" -eq 0 ]; then
        want=0
    else
        v=$(cat $B/voltage_now 2>/dev/null)
        i=$(cat $B/current_now 2>/dev/null)
        v=$(num "${v#-}" 0)
        # current_now: отрицательный - разряд, положительный - заряд (мкА).
        case "$i" in
            -*) i=$(num "${i#-}" 0) ;;
            *)  i=$(( -$(num "$i" 0) )) ;;
        esac
        # мкВ + мкА * мОм / 1000 = мкВ; итог в мВ
        ocv=$(( (v + i * res / 1000) / 1000 ))
        if [ "$v" -eq 0 ]; then
            :
        elif [ "$ocv" -lt "$mv" ]; then
            want=1
            high=0
        elif [ "$ocv" -ge $((mv + 50)) ]; then
            high=$((high + 1))
            [ "$high" -ge 2 ] && want=0
        else
            high=0
        fi
    fi
    if [ "$want" != "$state" ]; then
        state=$want
        setprop sys.rg52.lowbat "$state"
        log -t rg52-lowbat "lowbat $state (ocv ~${ocv} mV, threshold ${mv} mV)"
        am broadcast -a org.gammaos.rg52.action.LOWBAT_CHANGED > /dev/null 2>&1
        # Применение напрямую, а не через триггер init: oneshot-служба, уже
        # запущенная по другому поводу, повторный start пропустила бы.
        /system/bin/rg52-perf.sh
    fi
    sleep 20
done
